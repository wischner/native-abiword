const property_definition *find_property(std::string_view name) {
    const auto end = std::end(definitions);
    const auto found = std::lower_bound(
        std::begin(definitions), end, name,
        [](const property_definition &entry, std::string_view key) {
            return entry.name < key;
        });
    return found != end && found->name == name ? found : nullptr;
}

